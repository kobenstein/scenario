norm = lambda s: re.sub(r'[^a-z0-9]', '', s.lower())
SEC = {k: v.get('sec', k) for k, v in TM['sections'].items()}
def find(seg, phrase, nth=0):
    ws = [w for w in W if w['sec'] == seg]; q = [norm(p) for p in phrase.split() if norm(p)]; hit = 0
    for i in range(len(ws) - len(q) + 1):
        if all((norm(ws[i + j]['w']).startswith(p) if j == len(q) - 1 else norm(ws[i + j]['w']) == p) for j, p in enumerate(q)):
            if hit == nth: return ws[i]['s'], ws[i + len(q) - 1]['e']
            hit += 1
    raise SystemExit(f'phrase not found: {seg} "{phrase}" #{nth}')
S = lambda seg, ph, nth=0: find(seg, ph, nth)[0]
E = lambda seg, ph, nth=0: find(seg, ph, nth)[1]
CL = {c['id']: c for c in TM['clips']}
